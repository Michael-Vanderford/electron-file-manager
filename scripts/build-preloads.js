const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const output = path.join(root, 'src/main/generated');

// Bundle the existing CommonJS UI modules into static sandbox-compatible code.
// Electron remains the only runtime require; no eval or renderer Node access is used.
function bundle(entry) {
    const ids = new Map();
    const modules = [];
    function add(file) {
        if (ids.has(file)) return ids.get(file);
        const id = modules.length;
        ids.set(file, id); modules.push('');
        const source = fs.readFileSync(file, 'utf8').replace(/require\((['"])([^'"]+)\1\)/g, (_match, _quote, specifier) => {
            if (specifier === 'electron') return '__electron';
            if (specifier === 'path') return '__path';
            if (specifier === 'chart.js/auto') {
                const chart = path.resolve(path.dirname(require.resolve('chart.js/auto')), '../dist/chart.umd.js');
                return `__load(${add(chart)})`;
            }
            if (specifier.startsWith('.')) return `__load(${add(path.resolve(path.dirname(file), `${specifier}.js`))})`;
            throw new Error(`Unsupported sandbox preload import: ${specifier} in ${file}`);
        });
        modules[id] = `function(module, exports) {\n${source}\n}`;
        return id;
    }
    const entry_id = add(entry);
    // Internal Chromium URLs can skip native will-navigate; the isolated preload
    // also cancels Navigation API events before the page can replace itself.
    return `// Generated by scripts/build-preloads.js; edit the source modules instead.\n(() => {\n` +
        `const __electron = require('electron');\n` +
        `const __pageURL = window.location.href;\n` +
        `window.navigation.addEventListener('navigate', event => { if (event.destination.url !== __pageURL) event.preventDefault(); });\n` +
        `const __path = Object.fromEntries(['isAbsolute','resolve','relative','basename','dirname'].map(name => [name, (...args) => __electron.ipcRenderer.sendSync('path_operation', name, args)]));\n` +
        `const __modules = [${modules.join(',\n')}];\nconst __cache = {};\n` +
        `function __load(id) { if (__cache[id]) return __cache[id].exports; const module = { exports: {} }; __cache[id] = module; __modules[id](module, module.exports); return module.exports; }\n` +
        `__load(${entry_id});\n})();\n`;
}

function buildPreloads() {
    fs.mkdirSync(output, { recursive: true });
    for (const [name, source] of Object.entries({
        preload: 'src/main/preload.js',
        connect: 'src/renderer/dialogs/scripts/connect.js',
        columns: 'src/renderer/dialogs/scripts/columns.js'
    })) {
        const file = path.join(output, `${name}.js`);
        const contents = bundle(path.join(root, source));
        if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== contents) fs.writeFileSync(file, contents);
    }
}
if (require.main === module) buildPreloads();
module.exports = { buildPreloads };
